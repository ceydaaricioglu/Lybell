export const SUPPORTED_LOCALES: Locale[] = ['tr', 'en', 'de', 'fr', 'es'];

const LOCALE_LABELS: Record<Locale, string> = {
  tr: 'Türkçe',
  en: 'English',
  de: 'Deutsch',
  fr: 'Français',
  es: 'Español',
};

export function getLocaleLabel(locale: Locale): string {
  return LOCALE_LABELS[locale];
}

export function t(key: string, locale: Locale): string {
  return translations[locale]?.[key] ?? translations.tr[key] ?? key;
}

const VALID_LOCALES: Locale[] = ['tr', 'en', 'de', 'fr', 'es'];

export function getStoredLocale(): Locale {
  if (typeof window === 'undefined') return 'tr';
  const stored = localStorage.getItem('app_lang');
  return VALID_LOCALES.includes(stored as Locale) ? (stored as Locale) : 'tr';
}

export function setStoredLocale(locale: Locale): void {
  if (typeof window === 'undefined') return;
  localStorage.setItem('app_lang', locale);
}
